/* отзывы за месяц: {list:[{name,color,stars,id,text,who}], avg, units} */
function makeReviews(s, r){
  var m=r.month, ids=PROD_IDS.filter(function(id){ var x=r.rows[id]; return x && ((x.sold+x.contractUnits)>0 || x.lost>=3); });
  var items=[], totalUnits=0, starUnits=0, rng=rngFor(s,'rv'+m);
  ids.forEach(function(id){
    var x=r.rows[id], units=x.sold+x.contractUnits, ref=Math.max(1,refPrice(s,id)), ratio=x.price/ref, T=REV_TEXT[id], theme, stars;
    if(x.lost>=Math.max(3,x.demand*0.12) && rng()<0.75) theme='short';
    else if(r.fail>0.12 && rng()<0.7) theme='defect';
    else if(r.mode==='draft' && rng()<0.6) theme='draft';
    else if(ratio>1.22 && rng()<0.7) theme='expensive';
    else if(ratio<0.82 && rng()<0.6) theme='cheap';
    else { var sc=4.4+(r.mode==='fine'?0.5:0)+(s.rep-30)/120+(rng()-0.5)*1.3-(ratio>1.08?0.4:0); theme=sc>4.55?'praise':(sc>3.7?'mixed':'neutral'); }
    stars = {praise:5, mixed:4, neutral:3, short:3, defect:(r.fail>0.2?1:2), draft:2, expensive:3, cheap:5}[theme];
    if(units>0){ totalUnits+=units; starUnits+=units*stars; }
    var pool=T[theme]||T.neutral;
    items.push({id:id, units:Math.max(units,1), theme:theme, stars:stars, text:pool[Math.floor(rng()*pool.length)]});
  });
  /* выбираем до трёх отзывов: чем больше продано, тем вероятнее */
  var picked=[];
  while(items.length && picked.length<3){
    var tot=items.reduce(function(a,b){ return a+b.units; },0), roll=rng()*tot, k=0, acc=0;
    for(;k<items.length;k++){ acc+=items[k].units; if(roll<=acc) break; }
    picked.push(items.splice(Math.min(k,items.length-1),1)[0]);
  }
  /* имена без повторов */
  var names=REV_NAMES.slice(), list=picked.map(function(it,i){
    var ni=Math.floor(rng()*names.length), nm=names.splice(ni,1)[0];
    return {name:nm, color:REV_COLORS[hashStr(nm)%REV_COLORS.length], stars:it.stars, id:it.id, text:it.text, theme:it.theme};
  });
  /* редкая реплика героя заменяет последний отзыв */
  REV_SPECIAL.forEach(function(sp){
    if(list.length && sp.when(s,r) && rng()<sp.p && !list.some(function(l){ return l.special; })){
      list[list.length-1]={name:sp.who, color:'violet', stars:sp.stars, id:null, text:sp.t, theme:'special', special:true};
    }
  });
  return {list:list, avg: totalUnits>0 ? starUnits/totalUnits : 0, units: totalUnits};
}
