function upaWidth(i,n){ var t=i/(n-1); return 40+16*t+3*Math.sin(i*.09); }
function tulWidth(i,n){ var t=i/(n-1); return 17+8*t; }
function waterPoly(line,wf){
  var n=line.length, L=[], R=[], i;
  var nx=[], ny=[];
  for(i=0;i<n;i++){ var a=line[Math.max(0,i-1)], b=line[Math.min(n-1,i+1)], dx=b[0]-a[0], dy=b[1]-a[1], l=Math.sqrt(dx*dx+dy*dy)||1; nx.push(-dy/l); ny.push(dx/l); }
  for(i=0;i<n;i++){ var w=wf(i,n)/2; L.push([line[i][0]+nx[i]*w,line[i][1]+ny[i]*w]); R.push([line[i][0]-nx[i]*w,line[i][1]-ny[i]*w]); }
  return L.concat(R.reverse());
}
var UPA_POLY=waterPoly(UPA,upaWidth), TUL_POLY=waterPoly(TULITSA,tulWidth);

